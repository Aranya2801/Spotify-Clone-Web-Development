// How much better is smooth shuffle than random, and how close is it to
// the best possible order? With only 10 songs we can get the exact optimum
// with Held-Karp, so the comparison is honest.
//
//   node tools/evaluate.mjs            (prints a markdown table)
//   node tools/evaluate.mjs --runs 2000

import { readFileSync, writeFileSync } from 'node:fs';
import { TrackSpace, foldTempo, fifthsPosition } from '../js/similarity.js';
import { shuffleArray } from '../js/utils.js';

const runsArg = process.argv.indexOf('--runs');
const RUNS = runsArg > 0 ? +process.argv[runsArg + 1] : 1000;

const features = JSON.parse(readFileSync(new URL('../data/features.json', import.meta.url))).tracks;
const space = new TrackSpace(features);
const ids = space.ids;

// seeded so the numbers in the README are reproducible
let seed = 2024;
const rand = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};

// exact shortest open path that starts at `start` (Held-Karp, O(n^2 2^n))
function optimalFrom(start) {
  const n = ids.length;
  const s = ids.indexOf(start);
  const D = ids.map(a => ids.map(b => space.distance(a, b)));
  const FULL = 1 << n;
  const dp = Array.from({ length: FULL }, () => new Float64Array(n).fill(Infinity));
  const parent = Array.from({ length: FULL }, () => new Int8Array(n).fill(-1));
  dp[1 << s][s] = 0;
  for (let mask = 0; mask < FULL; mask++) {
    if (!(mask & (1 << s))) continue;
    for (let last = 0; last < n; last++) {
      const cur = dp[mask][last];
      if (cur === Infinity) continue;
      for (let nx = 0; nx < n; nx++) {
        if (mask & (1 << nx)) continue;
        const m2 = mask | (1 << nx);
        const v = cur + D[last][nx];
        if (v < dp[m2][nx]) {
          dp[m2][nx] = v;
          parent[m2][nx] = last;
        }
      }
    }
  }
  let best = Infinity;
  let end = -1;
  for (let i = 0; i < n; i++) if (dp[FULL - 1][i] < best) [best, end] = [dp[FULL - 1][i], i];
  const path = [];
  let mask = FULL - 1;
  while (end !== -1) {
    path.unshift(ids[end]);
    const p = parent[mask][end];
    mask ^= 1 << end;
    end = p;
  }
  return path;
}

function stats(order) {
  let bpmJump = 0;
  let keyOk = 0;
  for (let i = 1; i < order.length; i++) {
    const a = features[order[i - 1]];
    const b = features[order[i]];
    bpmJump += Math.abs(foldTempo(a.tempo) - foldTempo(b.tempo));
    const d = Math.abs(fifthsPosition(a.key) - fifthsPosition(b.key));
    if (Math.min(d, 12 - d) <= 1) keyOk++;
  }
  const t = order.length - 1;
  return { cost: space.pathCost(order), bpm: bpmJump / t, key: keyOk / t };
}

function avg(list) {
  const out = { cost: 0, bpm: 0, key: 0 };
  for (const s of list) for (const k in out) out[k] += s[k] / list.length;
  return out;
}

const random = [];
const greedy = [];
const smooth = [];
for (let i = 0; i < RUNS; i++) {
  const start = ids[i % ids.length];
  random.push(stats([start, ...shuffleArray(ids.filter(x => x !== start), rand)]));
  // greedy = smoothOrder without the 2-opt pass and without randomness
  const g = [start];
  const left = new Set(ids.filter(x => x !== start));
  while (left.size) {
    const last = g[g.length - 1];
    const nx = [...left].sort((a, b) => space.distance(last, a) - space.distance(last, b))[0];
    g.push(nx);
    left.delete(nx);
  }
  greedy.push(stats(g));
  smooth.push(stats(space.smoothOrder(ids, start, rand)));
}
const optimal = ids.map(id => stats(optimalFrom(id)));

const rows = [
  ['Random shuffle', avg(random)],
  ['Greedy nearest-neighbour', avg(greedy)],
  ['Smooth shuffle (ours)', avg(smooth)],
  ['Optimal (Held-Karp)', avg(optimal)],
];

const opt = avg(optimal).cost;
const rnd = avg(random).cost;
let md = `| Ordering | Path cost ↓ | vs. optimal | Avg tempo jump (bpm) ↓ | Key-compatible transitions ↑ |\n`;
md += `|---|---|---|---|---|\n`;
for (const [name, s] of rows) {
  md += `| ${name} | ${s.cost.toFixed(2)} | +${(((s.cost - opt) / opt) * 100).toFixed(1)}% | ${s.bpm.toFixed(1)} | ${(s.key * 100).toFixed(0)}% |\n`;
}
md += `\n${RUNS} runs per randomised method, ${ids.length} tracks. Smooth shuffle cuts total transition cost by ${(((rnd - avg(smooth).cost) / rnd) * 100).toFixed(0)}% compared with random.\n`;

console.log(md);
writeFileSync(new URL('../docs/evaluation.md', import.meta.url), `# Smooth shuffle evaluation\n\nGenerated by \`node tools/evaluate.mjs\`.\n\n${md}`);
